//! Pixar Universal Scene Description (USDA) Exporter and Importer
//!
//! Provides ASCII format (`#usda 1.0`) export and import for DAG scene graphs,
//! polymorphic geometry meshes, hierarchy transforms, materials, and lights.

use crate::node::{NodeData, NodeId, SceneNode};
use crate::scene::SceneGraph;
use core_math::{Mat4, Transform, Vec3};
use geo_kernel::{Mesh, VertexKey};
use slotmap::SecondaryMap;
use std::fs::File;
use std::io::{Read, Write};
use std::path::Path;

/// Exports an entire `SceneGraph` to a Pixar ASCII USDA string.
pub fn export_scene_to_usda(scene: &SceneGraph) -> String {
    let mut out = String::with_capacity(4096);
    out.push_str("#usda 1.0\n");
    out.push_str("(\n");
    out.push_str("    defaultPrim = \"World\"\n");
    out.push_str("    metersPerUnit = 1.0\n");
    out.push_str("    upAxis = \"Y\"\n");
    out.push_str("    doc = \"Generated by Plumb 3D Studio Engine (Pixar USD Interop)\"\n");
    out.push_str(")\n\n");

    out.push_str("def Xform \"World\"\n{\n");

    for &root_id in &scene.root_nodes {
        if let Some(root_node) = scene.nodes.get(root_id) {
            write_usda_node(scene, root_id, root_node, 1, &mut out);
        }
    }

    out.push_str("}\n");
    out
}

/// Recursively serializes a node and its children into USDA format.
fn write_usda_node(
    scene: &SceneGraph,
    _node_id: NodeId,
    node: &SceneNode,
    indent: usize,
    out: &mut String,
) {
    let pad = "    ".repeat(indent);
    let safe_name = sanitize_usd_identifier(&node.name);

    out.push_str(&format!("{}def Xform \"{}\"\n{}{{\n", pad, safe_name, pad));

    // Transform matrix
    let matrix = node.local_transform.to_matrix();
    write_usda_matrix(&matrix, indent + 1, out);

    // Node payload data
    match &node.data {
        NodeData::Mesh { base_mesh, .. } => {
            write_usda_mesh(base_mesh, &format!("{}_Mesh", safe_name), indent + 1, out);
        }
        NodeData::Light {
            color, intensity, ..
        } => {
            let l_pad = "    ".repeat(indent + 1);
            out.push_str(&format!(
                "{}def SphereLight \"{}_Light\"\n{}{{\n",
                l_pad, safe_name, l_pad
            ));
            out.push_str(&format!(
                "{}    float inputs:intensity = {:.2}\n",
                l_pad, intensity
            ));
            out.push_str(&format!(
                "{}    color3f inputs:color = ({:.3}, {:.3}, {:.3})\n",
                l_pad, color.x, color.y, color.z
            ));
            out.push_str(&format!("{}}}\n", l_pad));
        }
        NodeData::Camera {
            fov_y_radians,
            z_near,
            z_far,
            ..
        } => {
            let c_pad = "    ".repeat(indent + 1);
            let focal_length = 50.0 / (fov_y_radians.tan().max(0.01));
            out.push_str(&format!(
                "{}def Camera \"{}_Camera\"\n{}{{\n",
                c_pad, safe_name, c_pad
            ));
            out.push_str(&format!(
                "{}    float focalLength = {:.2}\n",
                c_pad, focal_length
            ));
            out.push_str(&format!(
                "{}    float2 clippingRange = ({:.2}, {:.2})\n",
                c_pad, z_near, z_far
            ));
            out.push_str(&format!("{}}}\n", c_pad));
        }
        _ => {}
    }

    // Recurse children
    for &child_id in &node.children {
        if let Some(child_node) = scene.nodes.get(child_id) {
            write_usda_node(scene, child_id, child_node, indent + 1, out);
        }
    }

    out.push_str(&format!("{}}}\n", pad));
}

fn write_usda_matrix(mat: &Mat4, indent: usize, out: &mut String) {
    let pad = "    ".repeat(indent);
    let cols = mat.to_cols_array_2d();
    out.push_str(&format!(
        "{}matrix4d xformOp:transform = ( ({}, {}, {}, {}), ({}, {}, {}, {}), ({}, {}, {}, {}), ({}, {}, {}, {}) )\n",
        pad,
        cols[0][0], cols[0][1], cols[0][2], cols[0][3],
        cols[1][0], cols[1][1], cols[1][2], cols[1][3],
        cols[2][0], cols[2][1], cols[2][2], cols[2][3],
        cols[3][0], cols[3][1], cols[3][2], cols[3][3],
    ));
    out.push_str(&format!(
        "{}uniform token[] xformOpOrder = [\"xformOp:transform\"]\n\n",
        pad
    ));
}

/// Writes a `geo_kernel::Mesh` as a `def Mesh` prim in USDA.
fn write_usda_mesh(mesh: &Mesh, mesh_name: &str, indent: usize, out: &mut String) {
    let pad = "    ".repeat(indent);
    out.push_str(&format!("{}def Mesh \"{}\"\n{}{{\n", pad, mesh_name, pad));

    let mut vertex_indices: SecondaryMap<VertexKey, usize> = SecondaryMap::new();
    let mut points: Vec<Vec3> = Vec::with_capacity(mesh.vertex_count());

    for (vk, vert) in mesh.vertices.iter() {
        vertex_indices.insert(vk, points.len());
        points.push(vert.position);
    }

    // Points
    out.push_str(&format!("{}    point3f[] points = [", pad));
    for (i, p) in points.iter().enumerate() {
        if i > 0 {
            out.push_str(", ");
        }
        out.push_str(&format!("({:.4}, {:.4}, {:.4})", p.x, p.y, p.z));
    }
    out.push_str("]\n");

    // Face counts & indices
    let mut face_counts: Vec<usize> = Vec::with_capacity(mesh.face_count());
    let mut face_indices: Vec<usize> = Vec::with_capacity(mesh.face_count() * 4);

    for (fk, _) in mesh.faces.iter() {
        let verts = mesh.face_vertices(fk);
        face_counts.push(verts.len());
        for vk in verts {
            if let Some(&idx) = vertex_indices.get(vk) {
                face_indices.push(idx);
            }
        }
    }

    out.push_str(&format!("{}    int[] faceVertexCounts = [", pad));
    for (i, c) in face_counts.iter().enumerate() {
        if i > 0 {
            out.push_str(", ");
        }
        out.push_str(&format!("{}", c));
    }
    out.push_str("]\n");

    out.push_str(&format!("{}    int[] faceVertexIndices = [", pad));
    for (i, idx) in face_indices.iter().enumerate() {
        if i > 0 {
            out.push_str(", ");
        }
        out.push_str(&format!("{}", idx));
    }
    out.push_str("]\n");

    out.push_str(&format!("{}}}\n", pad));
}

/// Exports the scene to a USDA file on disk.
pub fn export_scene_to_usda_file<P: AsRef<Path>>(
    scene: &SceneGraph,
    path: P,
) -> Result<(), std::io::Error> {
    let content = export_scene_to_usda(scene);
    let mut file = File::create(path)?;
    file.write_all(content.as_bytes())?;
    Ok(())
}

/// Parses a USDA ASCII string and populates a `SceneGraph`.
pub fn import_scene_from_usda(
    content: &str,
    scene: &mut SceneGraph,
) -> Result<Vec<NodeId>, String> {
    let mut imported_nodes = Vec::new();
    let mut points: Vec<Vec3> = Vec::new();
    let mut face_counts: Vec<usize> = Vec::new();
    let mut current_mesh_name = "ImportedMesh".to_string();

    for line in content.lines() {
        let trimmed = line.trim();

        if trimmed.starts_with("def Mesh") {
            if let Some(name_part) = trimmed.strip_prefix("def Mesh") {
                let name = name_part.trim().trim_matches('"');
                if !name.is_empty() {
                    current_mesh_name = name.to_string();
                }
            }
        } else if trimmed.starts_with("point3f[] points = [") {
            points = parse_usda_vec3_array(trimmed)?;
        } else if trimmed.starts_with("int[] faceVertexCounts = [") {
            face_counts = parse_usda_int_array(trimmed)?;
        } else if trimmed.starts_with("int[] faceVertexIndices = [") {
            let face_indices = parse_usda_int_array(trimmed)?;

            // When face indices are parsed, construct the Mesh
            if !points.is_empty() && !face_counts.is_empty() && !face_indices.is_empty() {
                let mut mesh = Mesh::new();
                let mut vkeys: Vec<VertexKey> = Vec::with_capacity(points.len());
                for &p in &points {
                    vkeys.push(mesh.add_vertex(p));
                }

                let mut cur_idx = 0;
                for &cnt in &face_counts {
                    if cur_idx + cnt <= face_indices.len() {
                        let face_vkeys: Vec<VertexKey> = (0..cnt)
                            .map(|i| vkeys[face_indices[cur_idx + i]])
                            .collect();
                        let _ = mesh.add_face(&face_vkeys);
                        cur_idx += cnt;
                    }
                }
                mesh.update_normals();

                let node = SceneNode::new_mesh(
                    current_mesh_name.clone(),
                    Transform::IDENTITY,
                    mesh,
                );
                let node_id = scene.add_node(node);
                imported_nodes.push(node_id);

                // Reset for next mesh
                points.clear();
                face_counts.clear();
            }
        }
    }

    if imported_nodes.is_empty() {
        return Err("No valid def Mesh primitives found in USDA file".to_string());
    }

    Ok(imported_nodes)
}

/// Imports USDA file from disk.
pub fn import_scene_from_usda_file<P: AsRef<Path>>(
    path: P,
    scene: &mut SceneGraph,
) -> Result<Vec<NodeId>, String> {
    let mut file = File::open(path).map_err(|e| e.to_string())?;
    let mut content = String::new();
    file.read_to_string(&mut content)
        .map_err(|e| e.to_string())?;
    import_scene_from_usda(&content, scene)
}

fn parse_usda_vec3_array(line: &str) -> Result<Vec<Vec3>, String> {
    let eq_idx = line.find('=').ok_or("Missing =")?;
    let bracket_slice = &line[eq_idx..];
    let start = bracket_slice.find('[').ok_or("Missing [")? + eq_idx;
    let end = line.rfind(']').ok_or("Missing ]")?;
    let inner = &line[start + 1..end];

    let mut points = Vec::new();
    let mut remainder = inner;
    while let Some(open) = remainder.find('(') {
        if let Some(close) = remainder[open..].find(')') {
            let coords_str = &remainder[open + 1..open + close];
            let coords: Vec<f32> = coords_str
                .split(',')
                .filter_map(|s| s.trim().parse::<f32>().ok())
                .collect();
            if coords.len() == 3 {
                points.push(Vec3::new(coords[0], coords[1], coords[2]));
            }
            remainder = &remainder[open + close + 1..];
        } else {
            break;
        }
    }
    Ok(points)
}

fn parse_usda_int_array(line: &str) -> Result<Vec<usize>, String> {
    let eq_idx = line.find('=').ok_or("Missing =")?;
    let bracket_slice = &line[eq_idx..];
    let start = bracket_slice.find('[').ok_or("Missing [")? + eq_idx;
    let end = line.rfind(']').ok_or("Missing ]")?;
    let inner = &line[start + 1..end];

    let ints: Vec<usize> = inner
        .split(',')
        .filter_map(|s| s.trim().parse::<usize>().ok())
        .collect();
    Ok(ints)
}

fn sanitize_usd_identifier(name: &str) -> String {
    let sanitized: String = name
        .chars()
        .map(|c| if c.is_alphanumeric() || c == '_' { c } else { '_' })
        .collect();
    if sanitized.is_empty()
        || sanitized
            .chars()
            .next()
            .map(|c| c.is_numeric())
            .unwrap_or(false)
    {
        format!("prim_{}", sanitized)
    } else {
        sanitized
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use geo_kernel::Primitives;

    #[test]
    fn test_usda_export_and_import_roundtrip() {
        let mut scene = SceneGraph::new();
        let cube = Primitives::create_cube(2.0);
        let node = SceneNode::new_mesh("TestCube".to_string(), Transform::IDENTITY, cube);
        scene.add_node(node);

        let usda = export_scene_to_usda(&scene);
        assert!(usda.contains("#usda 1.0"));
        assert!(usda.contains("def Xform \"TestCube\""));
        assert!(usda.contains("def Mesh \"TestCube_Mesh\""));
        assert!(usda.contains("point3f[] points = ["));
        assert!(usda.contains("int[] faceVertexCounts = ["));

        let mut imported_scene = SceneGraph::new();
        let imported_ids = import_scene_from_usda(&usda, &mut imported_scene).unwrap();
        assert_eq!(imported_ids.len(), 1);

        let imported_node = imported_scene.nodes.get(imported_ids[0]).unwrap();
        if let NodeData::Mesh { ref base_mesh, .. } = imported_node.data {
            assert_eq!(base_mesh.vertex_count(), 8);
            assert_eq!(base_mesh.face_count(), 6);
        } else {
            panic!("Expected Mesh payload");
        }
    }
}
