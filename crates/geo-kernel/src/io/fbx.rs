use crate::mesh::Mesh;
use core_math::{vec3, Vec2, Vec3};
use std::collections::HashMap;
use std::fs::File;
use std::io::{self, Read, Write};
use std::path::Path;

impl Mesh {
    /// Serializes the half-edge mesh to standard Autodesk FBX 7.4 ASCII format.
    /// Preserves arbitrary N-gons, quads, triangles, UV coordinates, and vertex normals.
    /// Fully compatible with Autodesk Maya, 3ds Max, Blender, Unreal Engine 5, and Unity.
    pub fn export_fbx_ascii(&self, object_name: &str) -> String {
        let clean_name = if object_name.is_empty() {
            "PlumbObject"
        } else {
            object_name
        };

        let mut out = String::with_capacity(32 * 1024);

        // 1. FBX Header Extension & Metadata
        out.push_str("; FBX 7.4.0 project file\n");
        out.push_str("; Generated by Plumb 3D Studio (Pure Safe Rust Interchange)\n\n");
        out.push_str("FBXHeaderExtension:  {\n");
        out.push_str("    FBXHeaderVersion: 1003\n");
        out.push_str("    FBXVersion: 7400\n");
        out.push_str("    Creator: \"Plumb 3D Studio\"\n");
        out.push_str("}\n\n");

        out.push_str("GlobalSettings:  {\n");
        out.push_str("    Version: 1000\n");
        out.push_str("    Properties70:  {\n");
        out.push_str("        P: \"UpAxis\", \"int\", \"Integer\", \"\",1\n");
        out.push_str("        P: \"UpAxisSign\", \"int\", \"Integer\", \"\",1\n");
        out.push_str("        P: \"UnitScaleFactor\", \"double\", \"Number\", \"\",100.0\n");
        out.push_str("    }\n");
        out.push_str("}\n\n");

        // 2. Map VertexKeys to sequential 0-based indices
        let mut key_to_idx = HashMap::new();
        let mut ordered_positions = Vec::with_capacity(self.vertices.len());
        for (idx, (vk, v)) in self.vertices.iter().enumerate() {
            key_to_idx.insert(vk, idx);
            ordered_positions.push(v.position);
        }

        let num_vertices = ordered_positions.len();

        out.push_str("Objects:  {\n");
        out.push_str(&format!(
            "    Geometry: 1000000, \"Geometry::{}\", \"Mesh\" {{\n",
            clean_name
        ));

        // 3. Vertices (flattened XYZ coordinates)
        out.push_str(&format!("        Vertices: *{} {{\n", num_vertices * 3));
        out.push_str("            a: ");
        for (i, p) in ordered_positions.iter().enumerate() {
            if i > 0 {
                out.push(',');
            }
            out.push_str(&format!("{:.6},{:.6},{:.6}", p.x, p.y, p.z));
        }
        out.push_str("\n        }\n");

        // 4. PolygonVertexIndex (Autodesk standard: last vertex of each polygon is ~index = -(index + 1))
        let mut fbx_indices = Vec::new();
        let mut poly_normals = Vec::new();
        let mut poly_uvs = Vec::new();

        for (fk, _) in &self.faces {
            let v_keys = self.face_vertices(fk);
            if v_keys.len() < 3 {
                continue;
            }
            let n = v_keys.len();
            for (i, &vk) in v_keys.iter().enumerate() {
                let v_idx = key_to_idx[&vk] as i32;
                if i == n - 1 {
                    fbx_indices.push(-v_idx - 1);
                } else {
                    fbx_indices.push(v_idx);
                }

                if let Some(v) = self.vertices.get(vk) {
                    poly_normals.push(v.normal);
                    poly_uvs.push(v.uv);
                } else {
                    poly_normals.push(Vec3::Y);
                    poly_uvs.push(Vec2::ZERO);
                }
            }
        }

        out.push_str(&format!(
            "        PolygonVertexIndex: *{} {{\n",
            fbx_indices.len()
        ));
        out.push_str("            a: ");
        for (i, idx) in fbx_indices.iter().enumerate() {
            if i > 0 {
                out.push(',');
            }
            out.push_str(&idx.to_string());
        }
        out.push_str("\n        }\n");

        // 5. LayerElementNormal (Normals per polygon vertex)
        out.push_str("        LayerElementNormal: 0 {\n");
        out.push_str("            Version: 101\n");
        out.push_str("            Name: \"\"\n");
        out.push_str("            MappingInformationType: \"ByPolygonVertex\"\n");
        out.push_str("            ReferenceInformationType: \"Direct\"\n");
        out.push_str(&format!(
            "            Normals: *{} {{\n",
            poly_normals.len() * 3
        ));
        out.push_str("                a: ");
        for (i, n) in poly_normals.iter().enumerate() {
            if i > 0 {
                out.push(',');
            }
            out.push_str(&format!("{:.6},{:.6},{:.6}", n.x, n.y, n.z));
        }
        out.push_str("\n            }\n        }\n");

        // 6. LayerElementUV (UV coordinates per polygon vertex)
        out.push_str("        LayerElementUV: 0 {\n");
        out.push_str("            Version: 101\n");
        out.push_str("            Name: \"UVMap\"\n");
        out.push_str("            MappingInformationType: \"ByPolygonVertex\"\n");
        out.push_str("            ReferenceInformationType: \"Direct\"\n");
        out.push_str(&format!("            UV: *{} {{\n", poly_uvs.len() * 2));
        out.push_str("                a: ");
        for (i, uv) in poly_uvs.iter().enumerate() {
            if i > 0 {
                out.push(',');
            }
            out.push_str(&format!("{:.6},{:.6}", uv.x, uv.y));
        }
        out.push_str("\n            }\n        }\n");

        out.push_str("    }\n");
        out.push_str(&format!(
            "    Model: 2000000, \"Model::{}\", \"Mesh\" {{\n",
            clean_name
        ));
        out.push_str("        Version: 232\n");
        out.push_str("    }\n");
        out.push_str("}\n\n");

        // 7. Connections
        out.push_str("Connections:  {\n");
        out.push_str(&format!(
            "    ; Model to Geometry\n    C: \"OO\",1000000,2000000\n"
        ));
        out.push_str(&format!(
            "    ; Model to Scene Root\n    C: \"OO\",2000000,0\n"
        ));
        out.push_str("}\n");

        out
    }

    /// Parses an Autodesk FBX ASCII formatted string into a topological half-edge BMesh.
    pub fn import_fbx_ascii(fbx_str: &str) -> Result<Self, String> {
        let mut mesh = Mesh::new();

        // 1. Locate Vertices: *N { a: ... } block
        let vertices_block = extract_fbx_array(fbx_str, "Vertices:").ok_or_else(|| {
            "FBX Import error: missing 'Vertices:' block in FBX stream".to_string()
        })?;

        let mut positions = Vec::new();
        let mut pos_chunks = vertices_block.split(',');
        while let (Some(x_s), Some(y_s), Some(z_s)) =
            (pos_chunks.next(), pos_chunks.next(), pos_chunks.next())
        {
            let x: f32 = x_s
                .trim()
                .parse()
                .map_err(|e| format!("Invalid vertex X: {}", e))?;
            let y: f32 = y_s
                .trim()
                .parse()
                .map_err(|e| format!("Invalid vertex Y: {}", e))?;
            let z: f32 = z_s
                .trim()
                .parse()
                .map_err(|e| format!("Invalid vertex Z: {}", e))?;
            positions.push(vec3(x, y, z));
        }

        if positions.is_empty() {
            return Err("FBX Import error: 0 vertices parsed from FBX stream".to_string());
        }

        // Add vertices to BMesh
        let mut vertex_keys = Vec::with_capacity(positions.len());
        for p in &positions {
            let vk = mesh.add_vertex(*p);
            vertex_keys.push(vk);
        }

        // 2. Locate PolygonVertexIndex: *N { a: ... } block
        let indices_block = extract_fbx_array(fbx_str, "PolygonVertexIndex:")
            .ok_or_else(|| "FBX Import error: missing 'PolygonVertexIndex:' block".to_string())?;

        let mut current_polygon = Vec::new();
        for idx_str in indices_block.split(',') {
            let trimmed = idx_str.trim();
            if trimmed.is_empty() {
                continue;
            }
            let raw_idx: i32 = trimmed
                .parse()
                .map_err(|e| format!("Invalid polygon index '{}': {}", trimmed, e))?;

            if raw_idx < 0 {
                // Negative index signals end of polygon: real_index = -raw_idx - 1
                let real_idx = (-raw_idx - 1) as usize;
                if real_idx < vertex_keys.len() {
                    current_polygon.push(vertex_keys[real_idx]);
                }

                if current_polygon.len() >= 3 {
                    let _ = mesh.add_face(&current_polygon);
                }
                current_polygon.clear();
            } else {
                let real_idx = raw_idx as usize;
                if real_idx < vertex_keys.len() {
                    current_polygon.push(vertex_keys[real_idx]);
                }
            }
        }

        // Recalculate face and vertex normals
        mesh.update_normals();

        Ok(mesh)
    }

    /// Saves the mesh to an Autodesk FBX file on disk.
    pub fn save_fbx(&self, path: impl AsRef<Path>, name: &str) -> io::Result<()> {
        let fbx_content = self.export_fbx_ascii(name);
        let mut file = File::create(path)?;
        file.write_all(fbx_content.as_bytes())
    }

    /// Loads a mesh from an Autodesk FBX ASCII file on disk.
    pub fn load_fbx(path: impl AsRef<Path>) -> Result<Self, String> {
        let mut file = File::open(path).map_err(|e| format!("Failed to open FBX file: {}", e))?;
        let mut content = String::new();
        file.read_to_string(&mut content)
            .map_err(|e| format!("Failed to read FBX file: {}", e))?;
        Self::import_fbx_ascii(&content)
    }
}

/// Helper function to locate and extract an FBX array block contents between "a:" and closing "}"
fn extract_fbx_array<'a>(fbx_str: &'a str, block_prefix: &str) -> Option<&'a str> {
    let block_start = fbx_str.find(block_prefix)?;
    let slice_after = &fbx_str[block_start..];
    let a_tag = slice_after.find("a:")?;
    let content_start = block_start + a_tag + 2;

    let slice_content = &fbx_str[content_start..];
    let end_bracket = slice_content.find('}')?;
    Some(&slice_content[..end_bracket])
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_fbx_ascii_roundtrip_cube() {
        let mut original = Mesh::new();
        let v0 = original.add_vertex(vec3(-1.0, -1.0, 1.0));
        let v1 = original.add_vertex(vec3(1.0, -1.0, 1.0));
        let v2 = original.add_vertex(vec3(1.0, 1.0, 1.0));
        let v3 = original.add_vertex(vec3(-1.0, 1.0, 1.0));
        let _ = original.add_face(&[v0, v1, v2, v3]);

        let fbx_text = original.export_fbx_ascii("TestQuad");
        assert!(fbx_text.contains("FBXHeaderVersion: 1003"));
        assert!(fbx_text.contains("PolygonVertexIndex: *4"));
        assert!(
            fbx_text.contains("-4"),
            "Last index of 0..3 quad should be -(3) - 1 = -4"
        );

        let imported = Mesh::import_fbx_ascii(&fbx_text).expect("FBX parsing should succeed");
        assert_eq!(imported.vertices.len(), 4);
        assert_eq!(imported.faces.len(), 1);
    }
}
