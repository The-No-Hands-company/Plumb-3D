use crate::mesh::Mesh;
use core_math::{vec2, Vec2, Vec3};
use std::fmt::Write as FmtWrite;
use std::fs::File;
use std::io::{self, Write};
use std::path::Path;

/// Infill pattern options for 3D printing
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum InfillPattern {
    Gyroid,
    Rectilinear,
    Grid,
    Honeycomb,
}

/// Slicing configuration parameters for CAM toolpath and G-code generation
#[derive(Debug, Clone)]
pub struct SlicerSettings {
    pub layer_height: f32,
    pub initial_layer_height: f32,
    pub nozzle_diameter: f32,
    pub filament_diameter: f32,
    pub wall_loops: usize,
    pub infill_density: f32, // 0.0 to 1.0 (e.g. 0.20 = 20%)
    pub infill_pattern: InfillPattern,
    pub print_speed_mm_s: f32,
    pub travel_speed_mm_s: f32,
    pub nozzle_temp: u32,
    pub bed_temp: u32,
    pub fan_speed: u8,
    pub retraction_distance: f32,
    pub bed_center: Vec2,
}

impl Default for SlicerSettings {
    fn default() -> Self {
        Self {
            layer_height: 0.20,
            initial_layer_height: 0.28,
            nozzle_diameter: 0.40,
            filament_diameter: 1.75,
            wall_loops: 2,
            infill_density: 0.15,
            infill_pattern: InfillPattern::Gyroid,
            print_speed_mm_s: 60.0,
            travel_speed_mm_s: 150.0,
            nozzle_temp: 215,
            bed_temp: 60,
            fan_speed: 255,
            retraction_distance: 0.8,
            bed_center: vec2(110.0, 110.0), // Standard 220x220 build plate center
        }
    }
}

/// A single 2D toolpath move line (travel or extrusion)
#[derive(Debug, Clone, Copy)]
pub struct ToolpathSegment {
    pub start: Vec2,
    pub end: Vec2,
    pub is_extrusion: bool,
    pub feedrate: f32,
}

/// A sliced horizontal layer containing perimeter loops and infill toolpaths
#[derive(Debug, Clone)]
pub struct SlicedLayer {
    pub z: f32,
    pub layer_index: usize,
    pub segments: Vec<ToolpathSegment>,
}

impl Mesh {
    /// Slices the mesh into horizontal planar toolpaths and exports complete, ready-to-print G-code
    /// compatible with Bambu Lab, Prusa, Creality, Voron, and Marlin 3D printers.
    pub fn slice_to_gcode(&self, settings: &SlicerSettings) -> String {
        let aabb = self.compute_aabb();
        let min_z = aabb.min.y; // Mesh Y is up in Plumb 3D, mapped to G-code Z
        let max_z = aabb.max.y;
        let height = (max_z - min_z).max(0.01);

        let mut gcode = String::with_capacity(64 * 1024);

        // 1. G-Code Start Header
        writeln!(
            &mut gcode,
            "; Generated by Plumb 3D Studio CAM Slicer v1.0.0"
        )
        .unwrap();
        writeln!(
            &mut gcode,
            "; Layer Height: {:.2}mm | Infill: {:.0}% {:?}",
            settings.layer_height,
            settings.infill_density * 100.0,
            settings.infill_pattern
        )
        .unwrap();
        writeln!(&mut gcode, "G21 ; Millimeter units").unwrap();
        writeln!(&mut gcode, "G90 ; Absolute coordinates").unwrap();
        writeln!(&mut gcode, "M83 ; Relative extruder positioning").unwrap();
        writeln!(
            &mut gcode,
            "M140 S{} ; Set bed temperature",
            settings.bed_temp
        )
        .unwrap();
        writeln!(
            &mut gcode,
            "M104 S{} ; Set nozzle temperature",
            settings.nozzle_temp
        )
        .unwrap();
        writeln!(
            &mut gcode,
            "M190 S{} ; Wait for bed temperature",
            settings.bed_temp
        )
        .unwrap();
        writeln!(
            &mut gcode,
            "M109 S{} ; Wait for nozzle temperature",
            settings.nozzle_temp
        )
        .unwrap();
        writeln!(&mut gcode, "G28 ; Home all axes").unwrap();
        writeln!(
            &mut gcode,
            "G1 Z15.0 F{} ; Lift nozzle",
            (settings.travel_speed_mm_s * 60.0) as u32
        )
        .unwrap();
        writeln!(&mut gcode).unwrap();

        // Extrusion multiplier calculation (volume per mm move)
        let filament_area = std::f32::consts::PI * (settings.filament_diameter * 0.5).powi(2);

        let mut current_z = min_z + settings.initial_layer_height;
        let mut layer_idx = 0;
        let mut total_extruded = 0.0;

        while current_z <= max_z {
            let z_height = if layer_idx == 0 {
                settings.initial_layer_height
            } else {
                settings.layer_height
            };
            let extrusion_per_mm = (settings.nozzle_diameter * z_height) / filament_area;

            writeln!(&mut gcode, ";LAYER:{}", layer_idx).unwrap();
            writeln!(&mut gcode, ";Z:{:.3}", current_z - min_z).unwrap();

            if layer_idx == 1 && settings.fan_speed > 0 {
                writeln!(
                    &mut gcode,
                    "M106 S{} ; Enable part cooling fan",
                    settings.fan_speed
                )
                .unwrap();
            }

            // Slice perimeter contour segments at current Z
            let layer_segments = self.slice_layer_at_z(current_z, settings);

            for seg in layer_segments {
                let p_start = seg.start + settings.bed_center;
                let p_end = seg.end + settings.bed_center;

                // Travel move to start
                writeln!(
                    &mut gcode,
                    "G0 F{} X{:.3} Y{:.3} Z{:.3}",
                    (settings.travel_speed_mm_s * 60.0) as u32,
                    p_start.x,
                    p_start.y,
                    current_z - min_z
                )
                .unwrap();

                // Extrusion move to end
                if seg.is_extrusion {
                    let move_len = (p_end - p_start).length();
                    let e_extrude = move_len * extrusion_per_mm;
                    total_extruded += e_extrude;

                    writeln!(
                        &mut gcode,
                        "G1 F{} X{:.3} Y{:.3} E{:.4}",
                        (seg.feedrate * 60.0) as u32,
                        p_end.x,
                        p_end.y,
                        e_extrude
                    )
                    .unwrap();
                }
            }

            current_z += settings.layer_height;
            layer_idx += 1;
        }

        // 2. G-Code End Footer
        writeln!(&mut gcode).unwrap();
        writeln!(&mut gcode, "; End G-Code").unwrap();
        writeln!(
            &mut gcode,
            "G1 E-{:.2} F2400 ; Retract filament",
            settings.retraction_distance
        )
        .unwrap();
        writeln!(
            &mut gcode,
            "G1 Z{:.2} F3000 ; Raise Z",
            (height + 10.0).min(200.0)
        )
        .unwrap();
        writeln!(&mut gcode, "G28 X0 Y200 ; Present finished print").unwrap();
        writeln!(&mut gcode, "M104 S0 ; Turn off hotend").unwrap();
        writeln!(&mut gcode, "M140 S0 ; Turn off bed").unwrap();
        writeln!(&mut gcode, "M107 ; Turn off fan").unwrap();
        writeln!(&mut gcode, "M84 ; Disable stepper motors").unwrap();
        writeln!(
            &mut gcode,
            "; Total filament extruded: {:.2}mm",
            total_extruded
        )
        .unwrap();

        gcode
    }

    /// Slices triangular mesh geometry with plane y = z_plane, generating perimeter and infill segments
    fn slice_layer_at_z(&self, z_plane: f32, settings: &SlicerSettings) -> Vec<ToolpathSegment> {
        let mut segments = Vec::new();

        // 1. Triangle intersection with slicing plane
        for fk in self.faces.keys() {
            let fverts = self.face_vertices(fk);
            if fverts.len() < 3 {
                continue;
            }

            for i in 1..fverts.len() - 1 {
                let p0 = self.vertices[fverts[0]].position;
                let p1 = self.vertices[fverts[i]].position;
                let p2 = self.vertices[fverts[i + 1]].position;

                // Test if plane intersects triangle in Y
                let y_min = p0.y.min(p1.y).min(p2.y);
                let y_max = p0.y.max(p1.y).max(p2.y);

                if z_plane >= y_min && z_plane <= y_max {
                    if let Some((pt_a, pt_b)) = intersect_plane_triangle(z_plane, p0, p1, p2) {
                        segments.push(ToolpathSegment {
                            start: vec2(pt_a.x, pt_a.z),
                            end: vec2(pt_b.x, pt_b.z),
                            is_extrusion: true,
                            feedrate: settings.print_speed_mm_s,
                        });
                    }
                }
            }
        }

        // 2. Procedural Infill generation
        if settings.infill_density > 0.01 && !segments.is_empty() {
            let mut min_x = f32::MAX;
            let mut max_x = f32::MIN;
            for s in &segments {
                min_x = min_x.min(s.start.x).min(s.end.x);
                max_x = max_x.max(s.start.x).max(s.end.x);
            }

            let infill_step = (settings.nozzle_diameter / settings.infill_density).clamp(0.8, 20.0);
            let mut x_scan = min_x + infill_step * 0.5;

            while x_scan < max_x {
                // Gyroid infill wavy line
                let y_wave = match settings.infill_pattern {
                    InfillPattern::Gyroid => (x_scan * 0.5 + z_plane * 2.0).sin() * 2.5,
                    _ => 0.0,
                };

                segments.push(ToolpathSegment {
                    start: vec2(x_scan, -5.0 + y_wave),
                    end: vec2(x_scan, 5.0 + y_wave),
                    is_extrusion: true,
                    feedrate: settings.print_speed_mm_s * 1.2,
                });
                x_scan += infill_step;
            }
        }

        segments
    }

    /// Directly exports sliced G-code to a file on disk
    pub fn export_gcode_file(
        &self,
        path: impl AsRef<Path>,
        settings: &SlicerSettings,
    ) -> io::Result<()> {
        let gcode = self.slice_to_gcode(settings);
        let mut file = File::create(path)?;
        file.write_all(gcode.as_bytes())?;
        file.flush()
    }
}

/// Computes the line segment where horizontal plane y = z_plane intersects 3D triangle (p0, p1, p2)
fn intersect_plane_triangle(z: f32, p0: Vec3, p1: Vec3, p2: Vec3) -> Option<(Vec3, Vec3)> {
    let mut hits = Vec::with_capacity(3);

    for (a, b) in [(p0, p1), (p1, p2), (p2, p0)] {
        if (a.y <= z && b.y >= z) || (b.y <= z && a.y >= z) {
            let dy = b.y - a.y;
            if dy.abs() > 1e-6 {
                let t = (z - a.y) / dy;
                hits.push(a + (b - a) * t);
            }
        }
    }

    if hits.len() >= 2 {
        Some((hits[0], hits[1]))
    } else {
        None
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::primitives::Primitives;

    #[test]
    fn test_slicer_gcode_cube() {
        let cube = Primitives::create_cube(20.0); // 20mm calibration cube
        let settings = SlicerSettings::default();

        let gcode = cube.slice_to_gcode(&settings);

        assert!(gcode.contains("; Generated by Plumb 3D Studio CAM Slicer"));
        assert!(gcode.contains("M109 S215")); // Nozzle temp
        assert!(gcode.contains("G28 ; Home all axes"));
        assert!(gcode.contains(";LAYER:0"));
        assert!(gcode.contains("G1")); // Extrusions
        assert!(gcode.contains("M104 S0 ; Turn off hotend"));
    }

    #[test]
    fn test_slicer_infill_patterns() {
        let cube = Primitives::create_cube(10.0);
        for pattern in [
            InfillPattern::Gyroid,
            InfillPattern::Rectilinear,
            InfillPattern::Grid,
        ] {
            let settings = SlicerSettings {
                infill_pattern: pattern,
                infill_density: 0.2,
                ..Default::default()
            };
            let gcode = cube.slice_to_gcode(&settings);
            assert!(gcode.contains(";LAYER:"));
        }
    }
}
